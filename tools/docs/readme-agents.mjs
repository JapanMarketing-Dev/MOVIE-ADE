// README.md / README.ja.md の「対応する Agent」のロゴ一覧を、docs/images/agents/agents.json（src/shared/agentLogos.ts から生成）から作り直す。
//   node tools/docs/readme-agents.mjs
// 各 README の <!-- agents:start --> と <!-- agents:end --> のあいだだけを書き換える。ロゴの無い Agent は汎用のアイコンにする。
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const PER_ROW = 6
const GENERIC = '.github/assets/agent-generic.svg'
const MORE = { 'README.md': '…and any CLI agent', 'README.ja.md': '…ほか、CLI で動く Agent なら何でも' }

const { agents } = JSON.parse(readFileSync(join(ROOT, 'docs/images/agents/agents.json'), 'utf8'))
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')

function grid(more) {
  const cells = agents.map(
    (a) =>
      `<td align="center" width="${Math.floor(100 / PER_ROW)}%"><a href="${esc(a.homepageUrl)}"><img src="${a.icon ?? GENERIC}" width="32" height="32" alt=""><br><sub>${esc(a.name)}</sub></a></td>`,
  )
  cells.push(`<td align="center"><sub>${more}</sub></td>`)
  const rows = []
  for (let i = 0; i < cells.length; i += PER_ROW) rows.push(`  <tr>\n    ${cells.slice(i, i + PER_ROW).join('\n    ')}\n  </tr>`)
  return `<!-- agents:start (generated by tools/docs/readme-agents.mjs from docs/images/agents/agents.json; do not edit by hand) -->\n<table>\n${rows.join('\n')}\n</table>\n<!-- agents:end -->`
}

for (const file of Object.keys(MORE)) {
  const path = join(ROOT, file)
  const before = readFileSync(path, 'utf8')
  const after = before.replace(/<!-- agents:start[\s\S]*?<!-- agents:end -->/, grid(MORE[file]))
  if (after === before && !before.includes('<!-- agents:start')) throw new Error(`${file} に <!-- agents:start --> … <!-- agents:end --> がありません`)
  writeFileSync(path, after)
  console.log(`${file}: ${agents.length} agents`)
}
